struct Target {
    int param;
    float amount;   // x the stored range per unit of the macro
};
struct Macro {
    const char* name;
    bool bipolar;
    std::vector<Target> targets;
};
// M1 Cutoff, M2 Resonance, M3 Env Amt, M4 Decay (+ Release, F Decay), M5 LFO1
// Depth (unipolar), M6 Mix.
inline std::vector<Macro> macros(const float* o) {
    const float cut = std::clamp(o[ty::kCutoff] / 19984.0f, 0.02f, 0.4f);
    const float dec = std::clamp(std::max(o[ty::kDecay], o[ty::kRelease]) / 30.0f, 0.005f, 0.2f);
    return {{"Cutoff", true, {{ty::kCutoff, cut}}},
            {"Resonance", true, {{ty::kResonance, 0.3f}}},
            {"Env Amt", true, {{ty::kEnvAmt, 0.25f}}},
            {"Decay", true, {{ty::kDecay, dec}, {ty::kRelease, dec}, {ty::kFDecay, dec}}},
            {"LFO1 Depth", false, {{ty::kLfo1Depth, 0.5f}}},
            {"Mix", true, {{ty::kMix, 0.25f}}}};
}
// M7 (Velocity) beside the Init's Volume target: Volume's amount from the amp
// velocity sense (the original: -15 dB x sens / 64 at velocity 0), Env Amt
// with the filter velocity switch.
inline float velocityVolume(const int32_t* v) { return float(1.0 - std::pow(10.0, -0.75 * v[kAmpVelSens] / 64.0)); }
inline std::vector<Target> velocityExtra(const int32_t* v) {
    if (v[kFilterVelSwitch]) return {{ty::kEnvAmt, 0.5f}};
    return {};
}

