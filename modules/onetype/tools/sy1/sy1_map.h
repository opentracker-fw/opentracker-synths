// --- the file -----------------------------------------------------------------------

struct Patch {
    std::string name;
    int version = 0;
    int lines = 0;   // the index,value lines read (0: not a patch)
    int32_t v[kCount];
    bool legacy() const { return version < 112; }
};

inline int32_t clampValue(int id, long x) {
    return int32_t(x < kParams[id].min ? kParams[id].min : (x > kParams[id].max ? kParams[id].max : x));
}
inline Patch defaults() {
    Patch p;
    for (int i = 0; i < kCount; ++i) p.v[i] = kParams[i].def;
    return p;
}

inline bool parseInt(std::string s, long& out) {
    while (!s.empty() && (s.front() == ' ' || s.front() == '\t')) s.erase(s.begin());
    while (!s.empty() && (s.back() == ' ' || s.back() == '\t')) s.pop_back();
    if (s.empty()) return false;
    char* end = nullptr;
    out = std::strtol(s.c_str(), &end, 10);
    return end && *end == '\0';
}

// The version groups the original converts (no ver line = 100; any other
// version, 101..104 and 109+ included, is read as it is).
inline int legacyGroup(int version) {
    switch (version) {
        case 0:
        case 100: return legacy::kVer100;
        case 105:
        case 106: return legacy::kVer105;
        case 107:
        case 108: return legacy::kVer107;
        default: return 0;
    }
}
inline void convertLegacy(int32_t* v, int version) {
    const int group = legacyGroup(version);
    if (!group) return;
    int32_t old[kCount];
    std::copy(v, v + kCount, old);
    for (const auto& r : legacy::kRules)
        if (r.groups & group) v[r.param] = r.table < 0 ? r.value : legacy::kTables[r.table][std::clamp(old[r.param], 0, 127)];
    // the wheel senses pulled their target toward 127; now additive routing
    const int sens[2] = {kWheelSpeedSens, kWheelAmountSens}, target[2] = {kLfo1Depth, kLfo1Speed};
    for (int k = 0; k < 2; ++k) v[sens[k]] = 64 + old[sens[k]] * (127 - old[target[k]]) * 63 / (127 * 127);
    // unison was fixed per play mode before it had its knobs
    const bool mono = old[kPlayMode] != 0;
    v[kUnisonVoices] = mono ? 4 : 2;
    v[kUnisonDetune] = group == legacy::kVer107
                           ? legacy::kTables[mono ? legacy::kUnisonDetuneMono : legacy::kUnisonDetunePoly][std::clamp(old[kUnisonDetune], 0, 127)]
                           : (mono ? 70 : 48);
}

// Line 1 = the name, key=value header lines, index,value lines (missing
// lines keep the init value, out-of-range values are clamped: the original
// plays them as the nearest in-range value).
inline Patch parse(const std::string& text) {
    Patch p = defaults();
    bool first = true;
    size_t pos = text.compare(0, 3, "\xEF\xBB\xBF") == 0 ? 3 : 0;   // a UTF-8 BOM
    while (pos < text.size()) {
        size_t eol = text.find_first_of("\r\n", pos);
        if (eol == std::string::npos) eol = text.size();
        const std::string line = text.substr(pos, eol - pos);
        pos = eol + 1;
        if (line.find('\0') != std::string::npos) continue;   // not text (UTF-16, binary)
        if (first) {
            p.name = line;
            first = false;
            continue;
        }
        const size_t eq = line.find('=');
        if (eq != std::string::npos) {
            long x = 0;
            if (line.substr(0, eq) == "ver" && parseInt(line.substr(eq + 1), x)) p.version = int(x);
            continue;
        }
        const size_t comma = line.find(',');
        long id = 0, x = 0;
        if (comma != std::string::npos && parseInt(line.substr(0, comma), id) && parseInt(line.substr(comma + 1), x) && id >= 0 &&
            id < kCount) {
            p.v[id] = clampValue(int(id), x);
            ++p.lines;
        }
    }
    convertLegacy(p.v, p.version);
    return p;
}

// --- the knob laws -----------------------------------------------------------------------

constexpr double kFmRefInc = 261.6255653 / 44100.0;   // the FM deviation unit (cycles per sample)
// Tempo sync: 30 steps over the knob.
inline int syncStep(int speed) { return std::clamp(speed, 0, 127) * 30 / 128; }
inline double svfHz(int knob) { return 16.7 * std::exp2(knob / 12.624); }
// LP24 by its own table; LPDL (it plays as LP24) by LP24's too.
inline double cutoffHz(int type, int knob) { return type == 1 || type == 4 ? double(tables::kLadderCutoffHz[knob]) : svfHz(knob); }
inline double attackS(int v) { return tables::kAmpAttackSeconds[v]; }
inline double toOnePct(int v) { return 4.6 * tables::kEnvTauSeconds[v]; }   // decay / release: time to 1 % (4.6 time constants)
// FM: the deviation (1001^u - 1) / 2000 per sample, u the stored value.
inline double fmUnits(int v) {
    if (v <= 0) return 0.0;
    return std::log2(1.0 + 2000.0 * double(tables::kFmBeta[v]) * kFmRefInc) / std::log2(1001.0);
}
// Saturation: a = aMax (2^(10 s) - 1) / 1023.
inline double satUnits(int v) {
    const double a = tables::kSaturationA[v], aMax = tables::kSaturationA[127];
    return std::log2(1.0 + a * 1023.0 / aMax) / 10.0;
}
inline double lfoHz(int v) { return std::exp2(v / 12.0367) / 12.0; }
// Glide: the time to land (4.318 time constants: the aim 1.35 % past the note).
inline double glideS(int v) { return v > 0 ? std::log(1.0135 / 0.0135) * tables::kPortaTau[v] : 0.0; }

// The 50 parameters (out) and the two extension parameters Width, Spread (ext).
inline void toOnetype(const int32_t* v, float* out, float* ext = nullptr) {
    float* o = out;
    o[ty::kOsc1Wave] = float(v[kOsc1Shape]);
    double det = v[kOsc1Detune] / 127.0;
    if (v[kUnisonOn]) det = std::max(det, 0.5 * v[kUnisonDetune] / 127.0);   // what stays of unison
    o[ty::kOsc1Detune] = float(det);
    o[ty::kOsc1Fm] = float(std::min(1.0, fmUnits(v[kOsc1FM])));
    o[ty::kSubLevel] = float(v[kSubGain] / 127.0);
    o[ty::kSubWave] = float(v[kSubShape]);
    o[ty::kSubOctave] = float(v[kSubOctave]);
    o[ty::kOsc2Wave] = float(v[kOsc2Shape] - 1);
    o[ty::kOsc2Pitch] = float(tables::kOsc2PitchSemis[v[kOsc2Pitch]]);
    o[ty::kOsc2Fine] = float(tables::kFineCents[v[kOsc2Fine]]);
    o[ty::kOsc2Track] = float(v[kOsc2KbdTrack]);
    o[ty::kSync] = float(v[kOsc2Sync]);
    o[ty::kRing] = float(v[kOsc2Ring]);
    o[ty::kMix] = float(v[kOscMix] / 127.0);
    o[ty::kPulseWidth] = float(v[kOscPulseWidth] / 127.0);
    o[ty::kKeyShift] = float(v[kOscKeyShift]);
    o[ty::kFineTune] = float(tables::kFineCents[v[kOscFineTune]]);
    o[ty::kPhase] = float(v[kOscPhase] / 127.0);
    const int amt = v[kModEnvAmount];
    o[ty::kModAmount] = v[kModEnvOn] ? float((amt - 64) / (amt > 64 ? 63.0 : 64.0)) : 0.0f;
    o[ty::kModAttack] = float(attackS(v[kModEnvAttack]));
    o[ty::kModDecay] = float(toOnePct(v[kModEnvDecay]));
    o[ty::kModDest] = float(v[kModEnvDest]);
    o[ty::kFilterType] = float(v[kFilterType]);
    o[ty::kCutoff] = float(std::min(20000.0, cutoffHz(v[kFilterType], v[kFilterFreq])));
    o[ty::kResonance] = float(v[kFilterRes] / 127.0);
    o[ty::kEnvAmt] = float(std::clamp((v[kFilterAmount] - 64) * 1.984 / 125.0, -1.0, 1.0));
    o[ty::kKeyTrack] = tables::kKbdTrack[v[kFilterKbdTrack]];
    o[ty::kSaturation] = float(satUnits(v[kFilterSat]));
    o[ty::kFAttack] = float(attackS(v[kFilterAttack]));
    o[ty::kFDecay] = float(toOnePct(v[kFilterDecay]));
    o[ty::kFSustain] = float(v[kFilterSustain] / 127.0);
    o[ty::kFRelease] = float(toOnePct(v[kFilterRelease]));
    o[ty::kAttack] = float(attackS(v[kAmpAttack]));
    o[ty::kDecay] = float(toOnePct(v[kAmpDecay]));
    o[ty::kSustain] = tables::kAmpSustainLevel[v[kAmpSustain]];
    o[ty::kRelease] = float(toOnePct(v[kAmpRelease]));
    for (int k = 0; k < 2; ++k) {
        const int b = ty::kLfo1Dest + k * ty::kLfoStride;
        const int dest = k ? kLfo2Dest : kLfo1Dest, type = k ? kLfo2Type : kLfo1Type, speed = k ? kLfo2Speed : kLfo1Speed;
        const int depth = k ? kLfo2Depth : kLfo1Depth, on = k ? kLfo2On : kLfo1On;
        const int sync = k ? kLfo2TempoSync : kLfo1TempoSync, key = k ? kLfo2KeySync : kLfo1KeySync;
        o[b + ty::kLfoDest] = float(v[dest] - 1);
        o[b + ty::kLfoWave] = float(v[type]);
        o[b + ty::kLfoRate] = float(std::clamp(lfoHz(v[speed]), 0.08, 130.0));
        o[b + ty::kLfoDepth] = v[on] ? float(v[depth] / 127.0) : 0.0f;
        o[b + ty::kLfoSync] = v[sync] ? float(1 + syncStep(v[speed])) : 0.0f;
        o[b + ty::kLfoKeySync] = float(v[key]);
    }
    const int mode = v[kPlayMode], autoG = v[kPortaAuto];
    o[ty::kGlideMode] = float((mode == 2 ? ty::kLegato : ty::kAlways) + (autoG ? 1 : 0));
    o[ty::kGlideTime] = float(std::min(3.0, glideS(v[kPortaTime])));
    o[ty::kVolume] = std::min(2.0f, tables::kAmpGain[v[kAmpGain]]);
    if (ext) {
        ext[0] = 0.0f;   // Width
        ext[1] = v[kUnisonOn] ? float(std::fabs(v[kUnisonPan] - 64) / 64.0) : 0.0f;   // Spread: the unison pan spread
    }
}

